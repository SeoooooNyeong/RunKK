package com.a207.runkk.app.domain.avatar

/**
 * 접수한 셀카 작업을 화면 밖에서 끝까지 따라가게 맡긴다(design-oo 05-30 6.1, D-749). 구현은 api.avatar
 * WorkManagerSelfieJobFollower다. 화면을 떠나거나 앱을 내려도 조회·결과 적용·알림이 이어진다.
 */
interface SelfieJobFollower {
    /** 새로 접수한 작업을 따라간다. 앞에 따라가던 작업은 그만둔다. */
    fun follow(jobId: String)

    /**
     * 기기에 남은 작업을 따라가는 중이 아니면 이어 따라간다(로그인한 앱 시작, 얼굴 만들기 다시 들어옴, 서버 /current로 찾은 작업). 따라가는
     * 중이면 그대로 둔다(돌고 있는 조회를 끊지 않는다). 구현마다 [follow]와 다르게 정해야 해서 기본 구현이 없다(D-795).
     */
    fun resume(jobId: String)

    /**
     * 앞 화면(홈·얼굴 만들기가 보일 때, 앱이 다시 앞으로 올 때)이 기기에 남은 작업을 한 번 직접 확인한다(D-820). 끝났으면 결과를
     * 받아 적용하거나 실패를 남기고, 만드는 중이면 그대로 둔다. 남은 작업이 없으면 아무것도 묻지 않는다. 워커가 네트워크 제약으로 돌지
     * 못해도 앞 화면의 진행 표시가 남지 않게 한다. 워커와 겹쳐도 결과는 한 번만 처리한다.
     */
    suspend fun checkNow()

    /** 따라가기를 멈춘다(기본 캐릭터를 골랐을 때). */
    fun cancel()
}
