package com.a207.runkk.app.core.designsystem

/**
 * 기본 아바타 그림 종류(D-254, 피그마 재확인 2026-10-30). 장면마다 피그마의 자세를 따른다.
 * 결과 화면은 자유런 완료·승리·신기록·무승부가 기쁨, 패배가 슬픔이다.
 */
enum class AvatarExpression {
    /** 결과 화면 기쁨(브이 자세). */
    JOY,

    /** 결과 화면 패배. */
    SAD,

    /** 서 있는 모습(홈, 매칭·카운트다운, 과거의 나). */
    STAND,

    /** 달리는 모습(러닝 중, 다른 러너 프로필). */
    RUN,

    /** 얼굴만(동그란 칸: 홈 상단, 마이, 랭킹 행, 지도 마커). */
    FACE
}
