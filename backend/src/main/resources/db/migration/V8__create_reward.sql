-- reward 패키지 소유 테이블(설계 5.1.1, D12 리워드 파일: 잔액·적립 내역·보유 아이템).
-- 이중 적립·하루 상한은 지갑 행 잠금 + (member_id, reason, source_id) 고유 제약, 구매는 지갑 행 잠금 + (member_id, item_id) 고유 제약(5.3).

CREATE TABLE reward_wallet (
    member_id BIGINT  PRIMARY KEY,
    balance   INTEGER NOT NULL,
    version   BIGINT  NOT NULL,
    CONSTRAINT ck_reward_wallet_balance CHECK (balance >= 0)
);

CREATE TABLE reward_accrual (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT       NOT NULL REFERENCES reward_wallet (member_id) ON DELETE CASCADE,
    reason     VARCHAR(20)  NOT NULL,
    source_id  VARCHAR(40)  NOT NULL,
    amount     INTEGER      NOT NULL,
    accrued_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_reward_accrual_reason CHECK (reason IN ('VALID_RUN', 'BATTLE_WIN')),
    CONSTRAINT ck_reward_accrual_amount CHECK (amount > 0),
    CONSTRAINT uq_reward_accrual_source UNIQUE (member_id, reason, source_id)
);

-- 결과 화면 적립량 조회(6.5 "reward_accrual(reason, source_id) 고유 인덱스로 직접 조회")
CREATE INDEX idx_reward_accrual_source ON reward_accrual (reason, source_id);

CREATE TABLE owned_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT       NOT NULL REFERENCES reward_wallet (member_id) ON DELETE CASCADE,
    item_id      BIGINT       NOT NULL,
    purchased_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_owned_item UNIQUE (member_id, item_id)
);
