-- audit 패키지 소유 테이블(설계 5.1.1, D14 감사 로그). 추가 전용: 행을 고치지 않는다(6.1.11).
CREATE TABLE audit_record (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recorded_at  TIMESTAMP(6) NOT NULL,
    actor_id     VARCHAR(100) NOT NULL,
    actor_role   VARCHAR(20)  NOT NULL,
    action       VARCHAR(30)  NOT NULL,
    target_id    VARCHAR(100) NOT NULL,
    before_value TEXT,
    after_value  TEXT,
    CONSTRAINT ck_audit_record_actor_role
        CHECK (actor_role IN ('RUNNER', 'CREW_LEADER', 'OPERATOR', 'SYSTEM')),
    CONSTRAINT ck_audit_record_action
        CHECK (action IN ('SIGN_UP_CONSENT', 'CONSENT_CHANGE', 'ROUTE_DISPOSAL', 'WITHDRAWAL',
                          'LEADER_TRANSFER', 'CREW_DELETE', 'KICK', 'POST_FORCE_DELETE',
                          'CELEBRITY_REGISTER', 'CELEBRITY_DELETE', 'SETTING_CHANGE'))
);

-- 관리툴 조회(기간 + 행위 종류, 최신순, FR-177)와 6개월 정리(FR-176)
CREATE INDEX idx_audit_record_recorded_at ON audit_record (recorded_at);
CREATE INDEX idx_audit_record_action_recorded_at ON audit_record (action, recorded_at);

-- 추가 전용 보장: UPDATE를 거부한다. 보관 기한 정리(DELETE)는 허용한다.
CREATE FUNCTION audit_record_reject_update() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'audit_record is append-only';
END;
$$;

CREATE TRIGGER trg_audit_record_reject_update
    BEFORE UPDATE ON audit_record
    FOR EACH ROW EXECUTE FUNCTION audit_record_reject_update();
