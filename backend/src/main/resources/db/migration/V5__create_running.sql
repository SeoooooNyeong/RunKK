-- running 패키지 소유 테이블(설계 5.1.1, D2 러닝 기록 파일, 파기 지시).
-- 위치 포인트·심박은 압축 바이너리 열에 둔다(6.5, 부록 E E-11 제안). 목록·통계 조회는 이 열을 읽지 않는다.
CREATE TABLE run_record (
    record_id            VARCHAR(36)  PRIMARY KEY,
    member_id            BIGINT       NOT NULL,
    started_at           TIMESTAMP(6) NOT NULL,
    ended_at             TIMESTAMP(6) NOT NULL,
    distance_meters      BIGINT       NOT NULL,
    elapsed_millis       BIGINT       NOT NULL,
    average_pace_seconds INTEGER      NOT NULL,
    mode                 VARCHAR(10)  NOT NULL,
    card_kind            VARCHAR(12)  NOT NULL,
    battle_id            BIGINT,
    crew_run_post_id     BIGINT,
    valid                BOOLEAN      NOT NULL,
    judged               BOOLEAN      NOT NULL,
    score                DOUBLE PRECISION,
    weather_temperature  INTEGER,
    weather_sky          VARCHAR(10),
    point_count          INTEGER      NOT NULL,
    route_data           BYTEA,
    route_purged         BOOLEAN      NOT NULL,
    unstable_segments    TEXT         NOT NULL,
    heart_rate_data      BYTEA,
    heart_rate_purged    BOOLEAN      NOT NULL,
    heart_rate_avg       INTEGER,
    heart_rate_max       INTEGER,
    new_records          TEXT         NOT NULL,
    CONSTRAINT ck_run_record_mode CHECK (mode IN ('FREE', 'BATTLE', 'CREW_RUN')),
    CONSTRAINT ck_run_record_card_kind
        CHECK (card_kind IN ('FREE_RUN', 'BATTLE_RUN', 'SELF_RUN', 'CELEB_RUN', 'CREW_RUN')),
    CONSTRAINT ck_run_record_period CHECK (started_at < ended_at),
    CONSTRAINT ck_run_record_positive CHECK (distance_meters > 0 AND elapsed_millis > 0),
    CONSTRAINT ck_run_record_score CHECK ((valid AND score IS NOT NULL) OR (NOT valid AND score IS NULL))
);

-- 기록 목록·대시보드 날짜별 합(6.5), 최근 유효 기록·유효 순번 계산
CREATE INDEX idx_run_record_member_started ON run_record (member_id, started_at DESC);
CREATE INDEX idx_run_record_member_valid_started ON run_record (member_id, valid, started_at DESC);
-- 랭킹 집계(기간 안 유효 거리 합, 6.5)
CREATE INDEX idx_run_record_valid_started ON run_record (started_at, member_id) WHERE valid;
-- 고스트 후보(경로가 남은 유효 기록, A-07)
CREATE INDEX idx_run_record_ghost ON run_record (member_id, distance_meters)
    WHERE valid AND NOT route_purged AND point_count > 0;

-- 회원별 최고 기록 장부. 같은 회원의 업로드를 이 행의 잠금으로 직렬화한다(5.3, D-37).
CREATE TABLE personal_record_book (
    member_id               BIGINT PRIMARY KEY,
    longest_record_id       VARCHAR(36),
    longest_elapsed_millis  BIGINT,
    longest_distance_meters BIGINT,
    longest_achieved_on     DATE,
    longest_has_unstable    BOOLEAN
);

CREATE TABLE personal_best (
    member_id       BIGINT      NOT NULL REFERENCES personal_record_book (member_id) ON DELETE CASCADE,
    distance_key    VARCHAR(10) NOT NULL,
    record_id       VARCHAR(36),
    elapsed_millis  BIGINT,
    distance_meters BIGINT,
    achieved_on     DATE,
    has_unstable    BOOLEAN,
    PRIMARY KEY (member_id, distance_key),
    CONSTRAINT ck_personal_best_distance CHECK (distance_key IN ('KM1', 'KM3', 'KM5', 'KM10', 'HALF'))
);

-- 위치·심박 동의 철회 뒤 7일 기한의 원자료 파기 지시(상태도 2.4.10)
CREATE TABLE disposal_order (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id           BIGINT       NOT NULL,
    kind                VARCHAR(12)  NOT NULL,
    due_at              TIMESTAMP(6) NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    executed_at         TIMESTAMP(6),
    device_confirmed_at TIMESTAMP(6),
    CONSTRAINT ck_disposal_order_kind CHECK (kind IN ('ROUTE', 'HEART_RATE')),
    CONSTRAINT ck_disposal_order_status CHECK (status IN ('SCHEDULED', 'EXECUTED', 'DEVICE_CONFIRMED'))
);

CREATE INDEX idx_disposal_order_scheduled ON disposal_order (status) WHERE status = 'SCHEDULED';
CREATE INDEX idx_disposal_order_member ON disposal_order (member_id);
