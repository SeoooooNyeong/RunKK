-- battle 패키지 소유 테이블(설계 5.1.1, D4 대결 파일, D16 가상 기록, 유명인 기록).
-- 매칭 대기열·진행 중 대결 세션의 기본 저장소는 Redis이고, match_ticket·live_battle_session은 runkk.queue=jdbc 대안이다(D-07).

CREATE TABLE battle (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                        VARCHAR(10)  NOT NULL,
    distance_meters             BIGINT       NOT NULL,
    status                      VARCHAR(15)  NOT NULL,
    created_at                  TIMESTAMP(6) NOT NULL,
    start_at                    TIMESTAMP(6),
    countdown_ends_at           TIMESTAMP(6),
    max_ends_at                 TIMESTAMP(6),
    closed_at                   TIMESTAMP(6),
    opponent_kind               VARCHAR(12),
    opponent_record_id          VARCHAR(36),
    opponent_name               VARCHAR(40),
    opponent_tier               VARCHAR(10),
    opponent_arrival_millis     BIGINT,
    opponent_track              TEXT,
    opponent_pace_seconds       INTEGER,
    opponent_fastest_km_seconds INTEGER,
    opponent_arrives_at         TIMESTAMP(6),
    opponent_arrived_at         TIMESTAMP(6),
    opponent_verdict            VARCHAR(10),
    judged_at                   TIMESTAMP(6),
    corrected                   BOOLEAN      NOT NULL,
    winner_member_id            BIGINT,
    winner_opponent             BOOLEAN      NOT NULL,
    version                     BIGINT       NOT NULL,
    CONSTRAINT ck_battle_type CHECK (type IN ('RANDOM', 'GHOST', 'SELF', 'CELEBRITY')),
    CONSTRAINT ck_battle_status
        CHECK (status IN ('WAITING_START', 'IN_PROGRESS', 'COUNTDOWN', 'RESULT_PENDING', 'FINISHED')),
    CONSTRAINT ck_battle_opponent_kind
        CHECK (opponent_kind IS NULL OR opponent_kind IN ('RUN_RECORD', 'VIRTUAL', 'CELEBRITY')),
    CONSTRAINT ck_battle_opponent
        CHECK ((type = 'RANDOM' AND opponent_kind IS NULL) OR (type <> 'RANDOM' AND opponent_kind IS NOT NULL)),
    CONSTRAINT ck_battle_distance CHECK (distance_meters > 0)
);

-- 1초 시계(A-11): 출발·카운트다운·최대 시간·기록 상대 도착·보류 만료
CREATE INDEX idx_battle_status_start ON battle (status, start_at);
CREATE INDEX idx_battle_status_countdown ON battle (status, countdown_ends_at);
CREATE INDEX idx_battle_status_max_ends ON battle (status, max_ends_at);
CREATE INDEX idx_battle_status_opponent_arrives ON battle (status, opponent_arrives_at);

CREATE TABLE battle_participant (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    battle_id        BIGINT      NOT NULL REFERENCES battle (id) ON DELETE CASCADE,
    seq              INTEGER,
    member_id        BIGINT      NOT NULL,
    arrived_at       TIMESTAMP(6),
    record_id        VARCHAR(36),
    verified         BOOLEAN,
    reach_millis     BIGINT,
    overtakes        INTEGER     NOT NULL,
    forfeited        BOOLEAN     NOT NULL,
    verdict          VARCHAR(10),
    max_lead_meters  BIGINT,
    max_trail_meters BIGINT,
    new_record       BOOLEAN     NOT NULL,
    CONSTRAINT ck_battle_participant_verdict CHECK (verdict IS NULL OR verdict IN ('WIN', 'LOSE', 'DRAW')),
    CONSTRAINT uq_battle_participant_member UNIQUE (battle_id, member_id)
);

-- 활성 대결 확인(FR-080, 탈퇴 차단)·이력(FR-101)·주간 전적
CREATE INDEX idx_battle_participant_member ON battle_participant (member_id);

CREATE TABLE battle_disconnection (
    participant_id  BIGINT       NOT NULL REFERENCES battle_participant (id) ON DELETE CASCADE,
    seq             INTEGER      NOT NULL,
    disconnected_at TIMESTAMP(6) NOT NULL,
    reconnected_at  TIMESTAMP(6),
    PRIMARY KEY (participant_id, seq)
);

-- 고스트 후보가 없을 때의 가상 기록 100개(FR-104). 회원 닉네임과 겹치지 않는다(D-45).
CREATE TABLE virtual_record (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tier          VARCHAR(10) NOT NULL,
    distance      VARCHAR(10) NOT NULL,
    nickname      VARCHAR(20) NOT NULL,
    finish_millis BIGINT      NOT NULL,
    CONSTRAINT uq_virtual_record_nickname UNIQUE (nickname),
    CONSTRAINT ck_virtual_record_tier CHECK (tier IN ('BRONZE', 'SILVER', 'GOLD', 'PLATINUM', 'MASTER')),
    CONSTRAINT ck_virtual_record_finish CHECK (finish_millis > 0)
);

CREATE INDEX idx_virtual_record_tier_distance ON virtual_record (tier, distance);

-- 운영자가 등록한 유명인 공개 기록(FR-170). 실명·사진은 없다(FR-171).
CREATE TABLE celebrity_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anonymous_name  VARCHAR(20)  NOT NULL,
    distance_meters BIGINT       NOT NULL,
    finish_millis   BIGINT       NOT NULL,
    splits          TEXT,
    source_name     VARCHAR(100) NOT NULL,
    source_url      VARCHAR(500),
    registered_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_celebrity_record_positive CHECK (distance_meters > 0 AND finish_millis > 0)
);

CREATE INDEX idx_celebrity_record_distance ON celebrity_record (distance_meters, registered_at DESC);

-- D-07 대안: 매칭 대기열(기본 키로 중복 대기 방지, FOR UPDATE SKIP LOCKED로 짝 배정)
CREATE TABLE match_ticket (
    member_id     BIGINT       PRIMARY KEY,
    tier          VARCHAR(10)  NOT NULL,
    distance      VARCHAR(10)  NOT NULL,
    waiting_since TIMESTAMP(6) NOT NULL,
    status        VARCHAR(10)  NOT NULL,
    CONSTRAINT ck_match_ticket_status CHECK (status IN ('WAITING', 'ASSIGNED'))
);

CREATE INDEX idx_match_ticket_waiting ON match_ticket (status, waiting_since);

-- D-07 대안: 진행 중 랜덤 대결 세션(대결마다 한 행, JSON)
CREATE TABLE live_battle_session (
    battle_id BIGINT PRIMARY KEY,
    snapshot  TEXT   NOT NULL
);
