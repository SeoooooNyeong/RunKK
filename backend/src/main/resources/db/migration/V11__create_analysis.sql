-- analysis 패키지 소유 테이블(설계 5.1.1, D3 러닝 목표 파일, D4 리포트 파일, D-25 랭킹 스냅숏).
-- 다른 패키지 테이블을 참조하지 않는다(D-32). 회원 ID는 식별자로만 둔다(D-02).

CREATE TABLE running_goal (
    member_id BIGINT PRIMARY KEY,
    version   BIGINT NOT NULL
);

CREATE TABLE weekly_goal (
    member_id       BIGINT  NOT NULL REFERENCES running_goal (member_id) ON DELETE CASCADE,
    week_start      DATE    NOT NULL,
    run_count       INTEGER NOT NULL,
    distance_meters BIGINT  NOT NULL,
    PRIMARY KEY (member_id, week_start),
    CONSTRAINT ck_weekly_goal_count CHECK (run_count BETWEEN 1 AND 7),
    CONSTRAINT ck_weekly_goal_distance CHECK (distance_meters > 0)
);

CREATE TABLE daily_plan (
    member_id           BIGINT  NOT NULL REFERENCES running_goal (member_id) ON DELETE CASCADE,
    plan_date           DATE    NOT NULL,
    distance_meters     BIGINT  NOT NULL,
    pace_seconds_per_km INTEGER,
    PRIMARY KEY (member_id, plan_date),
    CONSTRAINT ck_daily_plan_distance CHECK (distance_meters > 0)
);

-- 20시 계획 미이행 알림(FR-075): 그날 계획이 있는 회원
CREATE INDEX idx_daily_plan_date ON daily_plan (plan_date);

CREATE TABLE report (
    member_id              BIGINT           PRIMARY KEY,
    from_run               INTEGER          NOT NULL,
    to_run                 INTEGER          NOT NULL,
    average_score          DOUBLE PRECISION NOT NULL,
    distance_change_meters BIGINT           NOT NULL,
    pace_change_seconds    INTEGER          NOT NULL,
    frequent_day           VARCHAR(10)      NOT NULL,
    frequent_hour_band     INTEGER          NOT NULL,
    frequency_change       DOUBLE PRECISION NOT NULL,
    comment_text           VARCHAR(500),
    comment_source         VARCHAR(10),
    created_at             TIMESTAMP(6)     NOT NULL,
    version                BIGINT           NOT NULL,
    CONSTRAINT ck_report_runs CHECK (from_run >= 1 AND to_run >= from_run),
    CONSTRAINT ck_report_hour_band CHECK (frequent_hour_band BETWEEN 0 AND 7),
    CONSTRAINT ck_report_comment_source CHECK (comment_source IN ('AI', 'RULE'))
);

CREATE TABLE ranking_snapshot (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(10)  NOT NULL,
    period      VARCHAR(10)  NOT NULL,
    computed_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_ranking_snapshot_kind CHECK (kind IN ('PERSONAL', 'CREW')),
    CONSTRAINT ck_ranking_snapshot_period CHECK (period IN ('WEEKLY', 'MONTHLY'))
);

-- 최근 스냅숏 조회(D-25)
CREATE INDEX idx_ranking_snapshot_latest ON ranking_snapshot (kind, period, computed_at);

CREATE TABLE ranking_entry (
    snapshot_id     BIGINT      NOT NULL REFERENCES ranking_snapshot (id) ON DELETE CASCADE,
    entry_order     INTEGER     NOT NULL,
    rank_no         INTEGER     NOT NULL,
    subject_id      BIGINT      NOT NULL,
    display_name    VARCHAR(40) NOT NULL,
    tier            VARCHAR(10),
    distance_meters BIGINT      NOT NULL,
    PRIMARY KEY (snapshot_id, entry_order)
);
