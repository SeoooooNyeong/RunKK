-- crew 패키지 소유 테이블(설계 5.1.1, D8 크루·소속·가입 신청, D9 게시글·크루런, D10 크루 주간 거리).
-- 동시성(5.3): 정원은 crew 행 FOR UPDATE + Crew.admit, 1인 1크루·같은 크루 대기 중 신청 하나는 부분 고유 인덱스,
-- 주간 거리는 (crew_id, week_start, record_id) 고유 제약 + 원자적 증가, 크루런 대기실·투표는 낙관적 잠금(version).

CREATE TABLE crew (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(20)  NOT NULL,
    intro                  VARCHAR(40),
    tags                   VARCHAR(200) NOT NULL,
    visibility             VARCHAR(10)  NOT NULL,
    join_policy            VARCHAR(10)  NOT NULL,
    logo_url               VARCHAR(500),
    invite_code            VARCHAR(6)   NOT NULL,
    invite_code_expires_at TIMESTAMP(6) NOT NULL,
    created_at             TIMESTAMP(6) NOT NULL,
    version                BIGINT       NOT NULL,
    CONSTRAINT uq_crew_name UNIQUE (name),
    CONSTRAINT uq_crew_invite_code UNIQUE (invite_code),
    CONSTRAINT ck_crew_visibility CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT ck_crew_join_policy CHECK (join_policy IN ('APPROVAL', 'FREE'))
);

-- 목록(공개 크루, 최근 생성순, FR-117)
CREATE INDEX idx_crew_public_created ON crew (visibility, created_at DESC);

CREATE TABLE crew_membership (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id      BIGINT       NOT NULL REFERENCES crew (id) ON DELETE CASCADE,
    member_id    BIGINT       NOT NULL,
    role         VARCHAR(10)  NOT NULL,
    joined_at    TIMESTAMP(6) NOT NULL,
    left_at      TIMESTAMP(6),
    leave_reason VARCHAR(10),
    crew_intro   VARCHAR(40),
    crew_tags    VARCHAR(200) NOT NULL,
    CONSTRAINT ck_crew_membership_role CHECK (role IN ('LEADER', 'MEMBER')),
    CONSTRAINT ck_crew_membership_leave CHECK (leave_reason IS NULL OR leave_reason IN ('WITHDREW', 'KICKED'))
);

-- 1인 1크루(Q-34): 소속 중 행은 회원마다 하나
CREATE UNIQUE INDEX uq_crew_membership_active ON crew_membership (member_id) WHERE left_at IS NULL;
CREATE INDEX idx_crew_membership_crew ON crew_membership (crew_id);
CREATE INDEX idx_crew_membership_member ON crew_membership (member_id);

CREATE TABLE join_request (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id      BIGINT       NOT NULL,
    member_id    BIGINT       NOT NULL,
    requested_at TIMESTAMP(6) NOT NULL,
    status       VARCHAR(10)  NOT NULL,
    decided_at   TIMESTAMP(6),
    reason       VARCHAR(40),
    CONSTRAINT ck_join_request_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'DISSOLVED', 'CANCELLED', 'EXPIRED'))
);

-- 같은 크루에 대기 중 신청 하나(FR-121)
CREATE UNIQUE INDEX uq_join_request_pending ON join_request (crew_id, member_id) WHERE status = 'PENDING';
-- 3시 만료(Q-40)
CREATE INDEX idx_join_request_status_requested ON join_request (status, requested_at);
CREATE INDEX idx_join_request_member ON join_request (member_id);

-- 응원글·모집글(단일 테이블 상속, 구분 열 post_kind). 크루런 열은 모집글에만 있다.
CREATE TABLE crew_post (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_kind     VARCHAR(10)  NOT NULL,
    crew_id       BIGINT       NOT NULL,
    author_id     BIGINT,
    body          VARCHAR(200) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    deleted       BOOLEAN      NOT NULL,
    version       BIGINT       NOT NULL,
    scheduled_at  TIMESTAMP(6),
    distance      VARCHAR(10),
    vote_deadline TIMESTAMP(6),
    status        VARCHAR(12),
    departed_at   TIMESTAMP(6),
    ended_at      TIMESTAMP(6),
    reminded      BOOLEAN,
    CONSTRAINT ck_crew_post_kind CHECK (post_kind IN ('CHEER', 'CREW_RUN')),
    CONSTRAINT ck_crew_post_status
        CHECK (status IS NULL OR status IN ('VOTING', 'LOBBY_OPEN', 'RUNNING', 'FINISHED', 'CANCELLED')),
    CONSTRAINT ck_crew_post_distance CHECK (distance IS NULL OR distance IN ('KM1', 'KM3', 'KM5', 'KM10'))
);

-- 게시판 목록(최신순)과 1초 크루런 시계(A-13)
CREATE INDEX idx_crew_post_crew_created ON crew_post (crew_id, created_at DESC);
CREATE INDEX idx_crew_post_status_scheduled ON crew_post (status, scheduled_at);
CREATE INDEX idx_crew_post_author ON crew_post (author_id);

CREATE TABLE crew_run_participation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id          BIGINT       NOT NULL REFERENCES crew_post (id) ON DELETE CASCADE,
    member_id        BIGINT,
    voted_at         TIMESTAMP(6) NOT NULL,
    answer           VARCHAR(10)  NOT NULL,
    readiness        VARCHAR(12)  NOT NULL,
    runner           BOOLEAN      NOT NULL,
    arrived_at       TIMESTAMP(6),
    finish_rank      INTEGER,
    quit             BOOLEAN      NOT NULL,
    linked_record_id VARCHAR(36),
    CONSTRAINT ck_crew_run_participation_answer CHECK (answer IN ('GOING', 'NOT_GOING')),
    CONSTRAINT ck_crew_run_participation_readiness CHECK (readiness IN ('NOT_ENTERED', 'ENTERING', 'READY'))
);

-- 모집글마다 회원 한 번(FR-145), Runimal 동행 축 조회(FR-146)
CREATE UNIQUE INDEX uq_crew_run_participation ON crew_run_participation (post_id, member_id) WHERE member_id IS NOT NULL;
CREATE INDEX idx_crew_run_participation_member ON crew_run_participation (member_id);

-- 크루 주간 거리(6.2 A-12). 목표 거리 없음(N-15)
CREATE TABLE weekly_race (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id      BIGINT NOT NULL,
    week_start   DATE   NOT NULL,
    total_meters BIGINT NOT NULL,
    CONSTRAINT uq_weekly_race UNIQUE (crew_id, week_start),
    CONSTRAINT ck_weekly_race_total CHECK (total_meters >= 0)
);

CREATE TABLE race_contribution (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id    BIGINT      NOT NULL,
    week_start DATE        NOT NULL,
    member_id  BIGINT,
    record_id  VARCHAR(36) NOT NULL,
    meters     BIGINT      NOT NULL,
    CONSTRAINT uq_race_contribution UNIQUE (crew_id, week_start, record_id),
    CONSTRAINT ck_race_contribution_meters CHECK (meters >= 0)
);

-- 기록 상세의 크루 반영 거리(6.5, 길이 1)
CREATE INDEX idx_race_contribution_record ON race_contribution (record_id);
CREATE INDEX idx_race_contribution_member ON race_contribution (member_id);
