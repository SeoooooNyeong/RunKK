-- v0.11 S3b 크루 채팅(부록 F F.5.3 V23, FR-208~FR-210, FR-213, D-101) + 묶음 알림 동시성(D-102, 리뷰 M4).

-- 채팅 메시지. 크루 삭제(CrewDeletion.deleteAll이 crew 행을 지운다)는 FK CASCADE로 채팅을 지운다. 작성자가 탈퇴하면 author_id만
-- 비우고 내용은 남긴다(FR-021). content VARCHAR(500)은 글자(코드 포인트)로 센다(D-143). 위치 칼럼이 없다(NFR-021).
CREATE TABLE crew_chat_message (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id           BIGINT       NOT NULL REFERENCES crew (id) ON DELETE CASCADE,
    author_id         BIGINT,
    client_message_id VARCHAR(36)  NOT NULL,
    content           VARCHAR(500) NOT NULL,
    sent_at           TIMESTAMP(6) NOT NULL,
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    hidden            BOOLEAN      NOT NULL DEFAULT FALSE
);

-- 보내기 재전송 멱등(5.3): 같은 작성자의 같은 clientMessageId는 한 번만. 탈퇴로 작성자가 빈 행은 빼서 익명화가 충돌하지 않는다
CREATE UNIQUE INDEX uq_crew_chat_client ON crew_chat_message (author_id, client_message_id)
    WHERE author_id IS NOT NULL;
-- 메시지 ID 커서 조회(6.2 A-25: before·after·최신 세 갈래)
CREATE INDEX idx_crew_chat_message_crew_id ON crew_chat_message (crew_id, id DESC);
-- 탈퇴 익명화(ChatWithdrawalListener)
CREATE INDEX idx_crew_chat_message_author ON crew_chat_message (author_id);

-- 리액션. 기본 키 (message_id, member_id, kind)에 INSERT … ON CONFLICT DO NOTHING으로 멱등(FR-210)
CREATE TABLE crew_chat_reaction (
    message_id BIGINT       NOT NULL REFERENCES crew_chat_message (id) ON DELETE CASCADE,
    member_id  BIGINT       NOT NULL,
    kind       VARCHAR(10)  NOT NULL,
    reacted_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (message_id, member_id, kind),
    CONSTRAINT ck_crew_chat_reaction_kind CHECK (kind IN ('LIKE', 'HEART'))
);

-- 탈퇴 리액션 삭제(ChatReactionRepository.deleteByMember)
CREATE INDEX idx_crew_chat_reaction_member ON crew_chat_reaction (member_id);

-- 묶음 알림(CREW_CHAT, D-102): 같은 수신자·종류·대상의 읽지 않은 행은 하나(리뷰 M4). 혹시 이미 겹친 행이 있으면 가장 최근 행만 남긴다
DELETE FROM notification older
USING notification newer
WHERE older.type = 'CREW_CHAT'
  AND newer.type = 'CREW_CHAT'
  AND older.is_read = FALSE
  AND newer.is_read = FALSE
  AND older.recipient_id = newer.recipient_id
  AND older.target_id = newer.target_id
  AND older.id < newer.id;

CREATE UNIQUE INDEX uq_notification_unread_collapse ON notification (recipient_id, type, target_id)
    WHERE is_read = FALSE AND type = 'CREW_CHAT' AND target_id IS NOT NULL;
