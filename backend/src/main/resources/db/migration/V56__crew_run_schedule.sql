-- W6 크루 일정(S15P31A207-297) 스키마: 크루런 제목, 매주 반복(crew_run_series), 하프 거리. 데이터 옮기기(제목)는 V57.
-- 설계 근거: docs/sw/maintenance/2026-11-09_피그마맞춤-성/contract-W6.md 3절(반복 규칙), decisions.md C3·C4·C8.

-- 매주 반복 한 줄. 회차의 제목·내용·거리는 최신 회차(last_post_id)를 복사하고, 최신 회차 일시가 지나면 +7일 회차를 만든다.
-- last_post_id는 crew_post와 서로 참조하게 되어 FK를 두지 않는다(크루 삭제 때 글을 먼저 지우고 이 표를 지운다).
CREATE TABLE crew_run_series (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id           BIGINT       NOT NULL,
    author_id         BIGINT       NOT NULL,
    last_post_id      BIGINT       NOT NULL,
    last_scheduled_at TIMESTAMP(6) NOT NULL,
    active            BOOLEAN      NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    ended_at          TIMESTAMP(6),
    version           BIGINT       NOT NULL
);
-- 1분 작업(CrewRunRepeatJob)이 찾는 차례인 반복, 크루 삭제
CREATE INDEX idx_crew_run_series_due ON crew_run_series (last_scheduled_at) WHERE active;
CREATE INDEX idx_crew_run_series_crew ON crew_run_series (crew_id);

-- 크루런 제목(다른 종류는 NULL). 옛 본문 첫 줄이 200자까지 올 수 있어 열은 200자, 새 글은 서버가 30자로 막는다
ALTER TABLE crew_post ADD COLUMN title VARCHAR(200);
ALTER TABLE crew_post ADD COLUMN series_id BIGINT REFERENCES crew_run_series (id);

-- 같은 반복의 같은 일시 회차는 하나(작업이 겹쳐도 두 번 만들지 않는다). series_id가 NULL인 글은 서로 겹치지 않는다
CREATE UNIQUE INDEX uq_crew_post_series_scheduled ON crew_post (series_id, scheduled_at);

-- 지난 크루런 연·월 조회(GET /crews/{id}/crew-runs/past)
CREATE INDEX idx_crew_post_crew_run_past ON crew_post (crew_id, scheduled_at)
    WHERE post_kind = 'CREW_RUN' AND status IN ('FINISHED', 'CANCELLED');

-- 거리 선택지에 하프 추가(C4). 기존 1km 글이 남아 있어 KM1은 그대로 둔다(새 글은 서버가 막는다). 제한 없음은 NULL
ALTER TABLE crew_post DROP CONSTRAINT ck_crew_post_distance;
ALTER TABLE crew_post ADD CONSTRAINT ck_crew_post_distance
    CHECK (distance IS NULL OR distance IN ('KM1', 'KM3', 'KM5', 'KM10', 'HALF'));
