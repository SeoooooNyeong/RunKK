-- notification 패키지 소유 테이블(설계 5.1.1, D17 알림함, D-43 기기 토큰).
CREATE TABLE notification (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id  BIGINT       NOT NULL,
    type          VARCHAR(30)  NOT NULL,
    content       VARCHAR(500) NOT NULL,
    occurred_at   TIMESTAMP(6) NOT NULL,
    is_read       BOOLEAN      NOT NULL,
    target_screen VARCHAR(30),
    target_id     VARCHAR(100),
    CONSTRAINT ck_notification_type
        CHECK (type IN ('PLAN_MISSED', 'BODY_SHAPE_CHANGED', 'JOIN_REQUESTED', 'JOIN_DECIDED',
                        'JOIN_EXPIRED', 'LEADER_TRANSFERRED', 'CREW_DELETED', 'KICKED',
                        'CREW_RUN_RECRUIT', 'CREW_RUN_SOON', 'OPPONENT_ARRIVED', 'BATTLE_CORRECTED'))
);

-- 알림함(수신자별 최신순, FR-178), 보관 기한 정리(FR-175)
CREATE INDEX idx_notification_recipient_occurred ON notification (recipient_id, occurred_at DESC);
CREATE INDEX idx_notification_occurred ON notification (occurred_at);

-- 회원 기기 FCM 등록 토큰. 회원 ID와의 대응은 개인정보라 탈퇴 때 지운다(FR-021).
CREATE TABLE push_device (
    token         VARCHAR(512) PRIMARY KEY,
    member_id     BIGINT       NOT NULL,
    registered_at TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_push_device_member ON push_device (member_id);
