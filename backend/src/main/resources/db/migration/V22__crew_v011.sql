-- v0.11 S3a 크루 구조·게시 계층·사진·공동 목표(부록 F F.5.3 V22, D-98~D-100, D-104, D-105, D-106, D-125, D-154).

-- 게시 계층(D-99): 공지·게시글 본문 1,000자, 신고 숨김(D-104), 공지 고정(FR-205), 대면 모임 장소·정원(FR-132), 투표 방식·마감(FR-206)
ALTER TABLE crew_post ALTER COLUMN body TYPE VARCHAR(1000);
ALTER TABLE crew_post ADD COLUMN hidden BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE crew_post ADD COLUMN pinned BOOLEAN;
ALTER TABLE crew_post ADD COLUMN place_name VARCHAR(50);
ALTER TABLE crew_post ADD COLUMN capacity INTEGER;
ALTER TABLE crew_post ADD COLUMN poll_method VARCHAR(10);
ALTER TABLE crew_post ADD COLUMN poll_closes_at TIMESTAMP(6);

ALTER TABLE crew_post ADD CONSTRAINT ck_crew_post_meetup
    CHECK (post_kind <> 'MEETUP'
        OR (scheduled_at IS NOT NULL AND place_name IS NOT NULL AND capacity BETWEEN 2 AND 10));
ALTER TABLE crew_post ADD CONSTRAINT ck_crew_post_poll
    CHECK (post_kind <> 'POLL'
        OR (poll_method IN ('YES_NO', 'CHOICES') AND poll_closes_at IS NOT NULL));
ALTER TABLE crew_post ADD CONSTRAINT ck_crew_post_notice
    CHECK (post_kind <> 'NOTICE' OR pinned IS NOT NULL);

-- 고정 공지 수(CrewPostService.writeNotice·pin, crew 행 잠금 안에서 센다)와 투표 마감 1시간 전 알림(PollReminderJob, D-106·D-125)
CREATE INDEX idx_crew_post_pinned_notice ON crew_post (crew_id)
    WHERE post_kind = 'NOTICE' AND pinned AND NOT deleted;
CREATE INDEX idx_crew_post_poll_closing ON crew_post (poll_closes_at)
    WHERE post_kind = 'POLL' AND NOT deleted AND reminded = FALSE;

-- 대면 모임 참석 응답(FR-145)
CREATE TABLE crew_meetup_attendance (
    post_id     BIGINT       NOT NULL REFERENCES crew_post (id) ON DELETE CASCADE,
    member_id   BIGINT       NOT NULL,
    answer      VARCHAR(10)  NOT NULL,
    answered_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_crew_meetup_attendance PRIMARY KEY (post_id, member_id),
    CONSTRAINT ck_crew_meetup_attendance_answer CHECK (answer IN ('GOING', 'NOT_GOING', 'UNDECIDED'))
);
CREATE INDEX idx_crew_meetup_attendance_member ON crew_meetup_attendance (member_id);

-- 투표 선택지·응답(FR-206, FR-207). 응답은 회원당 하나, 선택지는 1~5번
CREATE TABLE crew_poll_option (
    post_id   BIGINT      NOT NULL REFERENCES crew_post (id) ON DELETE CASCADE,
    option_no SMALLINT    NOT NULL,
    label     VARCHAR(40) NOT NULL,
    CONSTRAINT pk_crew_poll_option PRIMARY KEY (post_id, option_no),
    CONSTRAINT ck_crew_poll_option_no CHECK (option_no BETWEEN 1 AND 5)
);

CREATE TABLE crew_poll_response (
    post_id      BIGINT       NOT NULL,
    member_id    BIGINT       NOT NULL,
    option_no    SMALLINT     NOT NULL,
    responded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_crew_poll_response PRIMARY KEY (post_id, member_id),
    CONSTRAINT fk_crew_poll_response_option FOREIGN KEY (post_id, option_no)
        REFERENCES crew_poll_option (post_id, option_no) ON DELETE CASCADE
);
CREATE INDEX idx_crew_poll_response_member ON crew_poll_response (member_id);

-- 게시글 사진(D-100): 메타와 바이트(BYTEA)를 한 표에 둔다. 메타 행을 먼저 넣고 같은 트랜잭션에서 jpeg를 채우므로 빈 바이트 기본값을 둔다.
CREATE TABLE crew_photo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT       NOT NULL REFERENCES crew_post (id) ON DELETE CASCADE,
    crew_id    BIGINT       NOT NULL,
    seq        SMALLINT     NOT NULL,
    size_bytes INTEGER      NOT NULL,
    jpeg       BYTEA        NOT NULL DEFAULT ''::bytea,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_crew_photo_post_seq UNIQUE (post_id, seq),
    CONSTRAINT ck_crew_photo_seq CHECK (seq BETWEEN 1 AND 5),
    CONSTRAINT ck_crew_photo_size CHECK (size_bytes BETWEEN 0 AND 1048576)
);
-- 앨범(최신순, 크루마다)
CREATE INDEX idx_crew_photo_crew ON crew_photo (crew_id, id DESC);

