-- v0.11 S3c 콘텐츠 신고(부록 F F.5.3 V24, 파일 D19, FR-214~FR-216, D-104, D-149).
-- 대상 하나에 report_case 한 행, 신고 한 건마다 content_report 한 행. crew 표에 FK를 걸지 않는다: 대상이 지워지면 사례는
-- "대상 없음"으로 남고 운영자가 기각한다(6.2 A-24).

CREATE TABLE report_case (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_kind         VARCHAR(15)  NOT NULL,
    target_id           BIGINT       NOT NULL,
    crew_id             BIGINT       NOT NULL,
    status              VARCHAR(12)  NOT NULL,
    open_reporter_count INTEGER      NOT NULL DEFAULT 0,
    opened_at           TIMESTAMP(6) NOT NULL,
    resolved_at         TIMESTAMP(6),
    resolver_id         VARCHAR(100),
    version             BIGINT       NOT NULL,
    -- 같은 대상의 동시 첫 신고는 INSERT … ON CONFLICT DO NOTHING으로 한 행만 만든다(5.3 신고 자동 숨김)
    CONSTRAINT uq_report_case_target UNIQUE (target_kind, target_id),
    CONSTRAINT ck_report_case_target_kind
        CHECK (target_kind IN ('CHEER', 'SCHEDULE', 'NOTICE', 'POLL', 'BOARD', 'CHAT_MESSAGE')),
    CONSTRAINT ck_report_case_status
        CHECK (status IN ('RECEIVED', 'AUTO_HIDDEN', 'HIDDEN', 'DISMISSED')),
    CONSTRAINT ck_report_case_open_reporter_count CHECK (open_reporter_count >= 0)
);

-- 관리툴 목록: 상태별 오래된 순(6.5 접근 경로)
CREATE INDEX idx_report_case_status_opened_at ON report_case (status, opened_at);

CREATE TABLE content_report (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id     BIGINT       NOT NULL REFERENCES report_case (id) ON DELETE CASCADE,
    reporter_id BIGINT,
    reason      VARCHAR(10)  NOT NULL,
    detail      VARCHAR(200),
    reported_at TIMESTAMP(6) NOT NULL,
    resolved    BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_content_report_reason
        CHECK (reason IN ('ABUSE', 'SEXUAL', 'SPAM', 'PRIVACY', 'OTHER'))
);

-- 같은 신고자는 같은 사례에 한 번만(기각 뒤에도, D-149). 탈퇴로 신고자가 빈 행은 빼서 익명화가 충돌하지 않는다
CREATE UNIQUE INDEX uq_content_report_reporter ON content_report (case_id, reporter_id)
    WHERE reporter_id IS NOT NULL;
-- 탈퇴 익명화(ReportWithdrawalListener)
CREATE INDEX idx_content_report_reporter ON content_report (reporter_id);
