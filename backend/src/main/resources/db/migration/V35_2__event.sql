CREATE TABLE event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                VARCHAR(40)  NOT NULL,
    title               VARCHAR(60)  NOT NULL,
    subtitle            VARCHAR(100) NOT NULL,
    kind                VARCHAR(20)  NOT NULL,
    config              TEXT         NOT NULL,
    starts_at           TIMESTAMP(6) NOT NULL,
    ends_at             TIMESTAMP(6) NOT NULL,
    banner_image_url    VARCHAR(300) NOT NULL,
    thumbnail_image_url VARCHAR(300) NOT NULL,
    detail_url          VARCHAR(300) NOT NULL,
    sort_order          INTEGER      NOT NULL,
    published           BOOLEAN      NOT NULL,
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_event_slug UNIQUE (slug),
    CONSTRAINT ck_event_kind CHECK (kind IN ('COACH_CELEB', 'RUN_DISTANCE')),
    CONSTRAINT ck_event_period CHECK (ends_at > starts_at)
);

-- 코치 승리 포인트는 회원·이벤트·대상(celebrity-11)마다 한 번만 준다
CREATE TABLE event_point_grant (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT       NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    event_id   BIGINT       NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    target_key VARCHAR(40)  NOT NULL,
    amount     INTEGER      NOT NULL,
    granted_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_event_point_grant UNIQUE (member_id, event_id, target_key),
    CONSTRAINT ck_event_point_grant_amount CHECK (amount > 0)
);

-- 이벤트 포인트 적립 사유(하루 상한 밖, 근거 = "이벤트 ID:대상")
