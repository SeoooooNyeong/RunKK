-- 크루 로고(피그마 F-04, S15P31A207-295): 게시 사진(crew_photo, D-100)처럼 위치 메타데이터를 지운 JPEG 바이트를 BYTEA로 둔다.
-- 크루를 만들기 전에 올리므로 크루 ID가 없다. 크루는 crew.logo_url(/api/v1/crew-logos/{id})로 가리킨다.
CREATE TABLE crew_logo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploader_id BIGINT       NOT NULL,
    size_bytes  INTEGER      NOT NULL,
    jpeg        BYTEA        NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_crew_logo_size CHECK (size_bytes BETWEEN 1 AND 1048576)
);
-- 회원별 업로드 조회(탈퇴 정리·남용 확인)
CREATE INDEX idx_crew_logo_uploader ON crew_logo (uploader_id, created_at DESC);
