-- member 패키지 소유 테이블(설계 5.1.1, D1 회원 파일). 탈퇴하면 식별정보 열이 NULL이 된다(FR-021).
CREATE TABLE member (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider                  VARCHAR(10),
    provider_account_id       VARCHAR(100),
    nickname                  VARCHAR(20),
    birth_year                INTEGER,
    gender                    VARCHAR(12),
    photo_url                 VARCHAR(500),
    intro                     VARCHAR(40),
    tags                      VARCHAR(200) NOT NULL,
    tier                      VARCHAR(10)  NOT NULL,
    level                     INTEGER      NOT NULL,
    joined_at                 TIMESTAMP(6) NOT NULL,
    -- MemberSettings
    unit                      VARCHAR(5)   NOT NULL,
    record_visibility         VARCHAR(10)  NOT NULL,
    course_map_shared         BOOLEAN      NOT NULL,
    profile_visibility        VARCHAR(10)  NOT NULL,
    muted_notification_types  VARCHAR(400) NOT NULL,
    watch_linked              BOOLEAN      NOT NULL,
    run_target                VARCHAR(10)  NOT NULL,
    run_voice                 BOOLEAN      NOT NULL,
    run_vibration             BOOLEAN      NOT NULL,
    run_follow_coach_plan     BOOLEAN      NOT NULL,
    battle_default_distance   VARCHAR(10)  NOT NULL,
    battle_voice              BOOLEAN      NOT NULL,
    battle_vibration          BOOLEAN      NOT NULL,
    battle_gap_alert_interval VARCHAR(10)  NOT NULL,
    -- TierProgress
    valid_run_count           INTEGER      NOT NULL,
    recent_scores             VARCHAR(200) NOT NULL,
    total_valid_meters        BIGINT       NOT NULL,
    status                    VARCHAR(10)  NOT NULL,
    withdrawn_at              TIMESTAMP(6),
    created_at                TIMESTAMP(6) NOT NULL,
    updated_at                TIMESTAMP(6) NOT NULL,
    version                   BIGINT       NOT NULL,
    CONSTRAINT uq_member_account UNIQUE (provider, provider_account_id),
    CONSTRAINT uq_member_nickname UNIQUE (nickname),
    CONSTRAINT ck_member_status CHECK (status IN ('ACTIVE', 'WITHDRAWN')),
    CONSTRAINT ck_member_tier
        CHECK (tier IN ('UNRANKED', 'BRONZE', 'SILVER', 'GOLD', 'PLATINUM', 'MASTER')),
    CONSTRAINT ck_member_record_visibility CHECK (record_visibility IN ('PUBLIC', 'CREW', 'PRIVATE')),
    CONSTRAINT ck_member_withdrawn
        CHECK ((status = 'ACTIVE' AND withdrawn_at IS NULL)
            OR (status = 'WITHDRAWN' AND withdrawn_at IS NOT NULL AND nickname IS NULL
                AND provider IS NULL AND provider_account_id IS NULL))
);

-- 탈퇴 7일 정리(WithdrawalService.purgeWithdrawn)
CREATE INDEX idx_member_withdrawn_at ON member (withdrawn_at) WHERE status = 'WITHDRAWN';
-- 고스트 주인·랭킹 대상(MemberQueryService.ghostEligibleOwners·rankedMemberIds, 6.5)
CREATE INDEX idx_member_tier_visibility ON member (tier, record_visibility) WHERE status = 'ACTIVE';

-- 동의 이력(FR-017). 덧붙이기만 하고 탈퇴 때 회원 행의 이력과 함께 지운다.
CREATE TABLE member_consent (
    member_id  BIGINT       NOT NULL REFERENCES member (id),
    seq        INTEGER      NOT NULL,
    item       VARCHAR(20)  NOT NULL,
    agreed     BOOLEAN      NOT NULL,
    changed_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (member_id, seq),
    CONSTRAINT ck_member_consent_item
        CHECK (item IN ('AGE_14_PLUS', 'TERMS', 'PRIVACY', 'LOCATION', 'MARKETING',
                        'HEART_RATE', 'FACE_TRANSFER', 'LLM_TRANSFER'))
);
