-- policy 패키지 소유 테이블(설계 5.1.1, D13 운영 기준 파일).
-- 기준값은 SettingKey별 JSON 문자열이다. 행이 없는 항목은 OperationPolicy가 srs.md 예시값을 쓴다.
CREATE TABLE operation_setting (
    setting_key   VARCHAR(40)  PRIMARY KEY,
    setting_value TEXT         NOT NULL,
    version       BIGINT       NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL
);

-- 기준값 변경 이력 {기준항목 + 변경전값 + 변경후값 + 변경일시} + 운영자 계정(FR-174)
CREATE TABLE operation_setting_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key  VARCHAR(40)  NOT NULL,
    before_value TEXT         NOT NULL,
    after_value  TEXT         NOT NULL,
    changed_at   TIMESTAMP(6) NOT NULL,
    operator_id  VARCHAR(100) NOT NULL
);

CREATE INDEX idx_operation_setting_history_key_changed_at
    ON operation_setting_history (setting_key, changed_at);
