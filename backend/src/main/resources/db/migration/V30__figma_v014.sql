-- v0.14 피그마 디자인 반영(설계 05-06 5.6.4, 05-08 D-291·D-294). 서버 DB 변경은 이 파일 하나다(D-249). V29는 analytics 스키마 MR(!49)이 쓴다.

-- 1. 친구 대결 초대(D-218~D-224). 대기 초대는 회원당 하나(부분 고유 인덱스), 참가됨이면 참가자·대결이 있어야 한다.
CREATE TABLE friend_invite (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inviter_member_id BIGINT       NOT NULL,
    distance_meters   BIGINT       NOT NULL,
    token             VARCHAR(32)  NOT NULL,
    status            VARCHAR(10)  NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    expires_at        TIMESTAMP(6) NOT NULL,
    joiner_member_id  BIGINT,
    battle_id         BIGINT,
    closed_at         TIMESTAMP(6),
    version           BIGINT       NOT NULL,
    CONSTRAINT uq_friend_invite_token UNIQUE (token),
    CONSTRAINT ck_friend_invite_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_friend_invite_distance CHECK (distance_meters IN (1000, 3000, 5000, 10000)),
    CONSTRAINT ck_friend_invite_accepted
        CHECK (status <> 'ACCEPTED' OR (joiner_member_id IS NOT NULL AND battle_id IS NOT NULL))
);

CREATE UNIQUE INDEX uq_friend_invite_pending ON friend_invite (inviter_member_id) WHERE status = 'PENDING';
-- 5초 만료 정리(FriendInviteExpiryJob)
CREATE INDEX idx_friend_invite_due ON friend_invite (expires_at) WHERE status = 'PENDING';

-- 2. 대결 종류 FRIEND(D-225). 친구 대결은 랜덤처럼 기록 상대가 없다.
ALTER TABLE battle DROP CONSTRAINT ck_battle_type;
ALTER TABLE battle ADD CONSTRAINT ck_battle_type
    CHECK (type IN ('RANDOM', 'GHOST', 'FRIEND', 'SELF', 'CELEBRITY'));
ALTER TABLE battle DROP CONSTRAINT ck_battle_opponent;
ALTER TABLE battle ADD CONSTRAINT ck_battle_opponent
    CHECK ((type IN ('RANDOM', 'FRIEND') AND opponent_kind IS NULL)
        OR (type NOT IN ('RANDOM', 'FRIEND') AND opponent_kind IS NOT NULL));

-- 3. 최고 기록 장부에 풀(42.195km) 칸(D-238). 기존 기록으로 소급하지 않는다.
ALTER TABLE personal_best DROP CONSTRAINT ck_personal_best_distance;
ALTER TABLE personal_best ADD CONSTRAINT ck_personal_best_distance
    CHECK (distance_key IN ('KM1', 'KM3', 'KM5', 'KM10', 'HALF', 'FULL'));

-- 4. 기록 목록 썸네일 경로 모양(D-234, 기존 기록은 RouteShapeBackfillJob)과 평가 표시(D-291·D-294, 기존 행은 NULL).
ALTER TABLE run_record ADD COLUMN route_shape TEXT;
ALTER TABLE run_record ADD COLUMN evaluation_kind VARCHAR(20);
ALTER TABLE run_record ADD COLUMN evaluation_tier VARCHAR(10);
ALTER TABLE run_record ADD COLUMN evaluation_valid_runs INTEGER;
ALTER TABLE run_record ADD COLUMN evaluation_runimal_type VARCHAR(20);
ALTER TABLE run_record ADD CONSTRAINT ck_run_record_evaluation_kind
    CHECK (evaluation_kind IS NULL OR evaluation_kind IN ('FIRST_PLACEMENT', 'REEVALUATION'));
ALTER TABLE run_record ADD CONSTRAINT ck_run_record_evaluation_valid_runs
    CHECK (evaluation_valid_runs IS NULL OR evaluation_valid_runs >= 3);
ALTER TABLE run_record ADD CONSTRAINT ck_run_record_evaluation_all
    CHECK ((evaluation_kind IS NULL AND evaluation_tier IS NULL AND evaluation_valid_runs IS NULL)
        OR (evaluation_kind IS NOT NULL AND evaluation_tier IS NOT NULL AND evaluation_valid_runs IS NOT NULL));

-- 5. 기록 삭제 묘비(D-232). 같은 기록 ID의 재업로드를 막는다. 회원 탈퇴 정리가 함께 지운다.
CREATE TABLE run_record_tombstone (
    record_id  VARCHAR(36)  PRIMARY KEY,
    member_id  BIGINT       NOT NULL,
    deleted_at TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_run_record_tombstone_member ON run_record_tombstone (member_id);

-- 6. 회원: 가이드 확인(D-244), 나이대·성별 항목별 공개(D-241, 기존 회원은 profile_visibility 값), 프로필 사진 값 비움(D-242, 열은 다음 버전에서 삭제).
