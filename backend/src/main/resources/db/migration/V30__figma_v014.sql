UPDATE member SET age_band_visibility = profile_visibility, gender_visibility = profile_visibility
    WHERE profile_visibility IN ('PUBLIC', 'PRIVATE');
ALTER TABLE member ADD CONSTRAINT ck_member_age_band_visibility
    CHECK (age_band_visibility IN ('PUBLIC', 'PRIVATE'));
ALTER TABLE member ADD CONSTRAINT ck_member_gender_visibility
    CHECK (gender_visibility IN ('PUBLIC', 'PRIVATE'));
UPDATE member SET photo_url = NULL WHERE photo_url IS NOT NULL;

-- 7. Runimal 확정 이력(D-245). 기존 확정 유형으로 채운다.
CREATE TABLE runimal_confirmed_history (
    member_id BIGINT      NOT NULL,
    type      VARCHAR(20) NOT NULL,
    PRIMARY KEY (member_id, type)
);

INSERT INTO runimal_confirmed_history (member_id, type)
SELECT member_id, confirmed_type FROM runimal_profile WHERE confirmed_type IS NOT NULL;

-- 8. Runimal 유형 비율 스냅숏(D-246). 첫 값은 배포 뒤 첫 0시 작업이 쓴다(그 전 조회는 sharePercent null).
CREATE TABLE runimal_type_share (
    type            VARCHAR(20)  PRIMARY KEY,
    confirmed_count INTEGER      NOT NULL,
    total_confirmed INTEGER      NOT NULL,
    computed_at     TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_runimal_type_share_count
        CHECK (confirmed_count >= 0 AND total_confirmed >= confirmed_count)
);

-- 9. 셀럽 실명 등록 동의(D-240). 동의 일시·근거는 둘 다 있거나 둘 다 없다.
