package com.a207.runkk.infra.battle;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/**
 * 셀럽 기록 10건(풀코스 4건과 이O주 하프·10km·5km, 연예인 3건, 2026-10-31 결정). develop·prod는 Flyway V32, local은
 * import-local.sql이 넣는다. 두 파일의 INSERT가 같고, local과 같은 H2(PostgreSQL 모드)에서 그대로 들어가는지 본다.
 */
@DisplayName("셀럽 기록 초기 데이터(V32·import-local.sql)")
class CelebritySeedTest {

    private static final Path MIGRATION =
            Path.of("src", "main", "resources", "db", "migration", "V32__celebrity_figure.sql");
    private static final Path LOCAL = Path.of("src", "main", "resources", "import-local.sql");

    private static List<String> inserts(Path file) throws IOException {
        return Files.readAllLines(file, StandardCharsets.UTF_8).stream()
                .map(String::strip)
                .filter(line -> line.startsWith("INSERT"))
                .toList();
    }

    @Test
    @DisplayName(
            "local 초기 데이터는 V32와 같은 10건이고 H2에 들어가 등록 시각 내림차순으로 풀코스 4건 뒤 이O주 하프·10km·5km, 연예인 3건다")
    void localSeed_matchesMigration_andLoads() throws IOException {
        List<String> local = inserts(LOCAL);
        assertThat(local).hasSize(10).isEqualTo(inserts(MIGRATION));

        JdbcTemplate jdbc =
                new JdbcTemplate(
                        new DriverManagerDataSource(
                                "jdbc:h2:mem:celebrity-seed;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1",
                                "sa",
                                ""));
        // V6 celebrity_record + V30 실명 동의 + V32 그림 키
        jdbc.execute(
                "CREATE TABLE celebrity_record (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY"
                        + " KEY, anonymous_name VARCHAR(20) NOT NULL, distance_meters BIGINT NOT"
                        + " NULL, finish_millis BIGINT NOT NULL, splits TEXT, source_name"
                        + " VARCHAR(100) NOT NULL, source_url VARCHAR(500), registered_at"
                        + " TIMESTAMP(6) NOT NULL, real_name_consented_at TIMESTAMP(6),"
                        + " real_name_consent_basis VARCHAR(200), figure_key VARCHAR(20))");
        local.forEach(sql -> jdbc.execute(sql.substring(0, sql.length() - 1)));

        List<Map<String, Object>> rows =
                jdbc.queryForList(
                        "SELECT anonymous_name, figure_key, distance_meters, finish_millis, splits,"
                                + " real_name_consented_at FROM celebrity_record ORDER BY"
                                + " registered_at DESC");
        assertThat(rows)
                .extracting(r -> r.get("anonymous_name"))
                .containsExactly(
                        "이O주", "황O조", "황O조", "손O정", "이O주", "이O주", "이O주", "기O84", "임O미", "진O규");
        assertThat(rows)
                .extracting(r -> r.get("figure_key"))
                .containsExactly(
                        "lee", "hwang", "hwang", "son", "lee", "lee", "lee", "gian", "lim", "jin");
        assertThat(rows)
                .extracting(r -> ((Number) r.get("finish_millis")).longValue())
                .containsExactly(
                        7_640_000L,
                        7_689_000L,
                        8_003_000L,
                        8_959_000L,
                        3_664_000L,
                        1_784_110L,
                        852_270L,
                        17_296_000L,
                        15_643_000L,
                        3_332_000L);
        assertThat(rows)
                .extracting(r -> ((Number) r.get("distance_meters")).longValue())
                .containsExactly(
                        42_195L, 42_195L, 42_195L, 42_195L, 21_097L, 10_000L, 5_000L, 42_195L,
                        42_195L, 10_000L);
        assertThat(rows)
                .allSatisfy(
                        r -> {
                            assertThat(r.get("splits")).as("구간 기록 없음").isNull();
                            assertThat(r.get("real_name_consented_at")).as("실명 동의 없음").isNull();
                        });
    }
}
